/* 按产品名匹配图片 URL；匹配不到返回 null
   type/name 任一命中即可，如 "5m智能窗帘（C200）" 命中 C200 规则 */
function productImg(type, name) {
  var hay = String(type || '') + '|' + String(name || '');
  for (var i = 0; i < PRODUCT_IMG_RULES.length; i++) {
    var rule = PRODUCT_IMG_RULES[i];
    if (hay.indexOf(rule[0]) > -1) {
      return PRODUCT_IMG_DIR + encodeURIComponent(rule[1]);
    }
  }
  return null;
}
